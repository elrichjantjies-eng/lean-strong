/**
 * Converts the shared weather icons (src/icons/defs.ts) into Android vector drawables for the
 * home-screen widgets and notifications, so the widgets use exactly the app's artwork.
 *
 *   node scripts/gen-android-icons.mjs
 *
 * Writes android/app/src/main/res/drawable/wx_*.xml and ic_stat_weather.xml.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { ICONS, GRADIENTS } from "../src/icons/defs.ts";

const out = "android/app/src/main/res/drawable";
mkdirSync(out, { recursive: true });

/** CSS #RGB / #RRGGBB / #RRGGBBAA → Android #AARRGGBB */
function color(css) {
  let h = css.slice(1);
  if (h.length === 3) h = [...h].map((c) => c + c).join("");
  if (h.length === 6) return `#FF${h.toUpperCase()}`;
  return `#${h.slice(6, 8)}${h.slice(0, 6)}`.toUpperCase();
}

const r2 = (n) => Math.round(n * 100) / 100;

function shapePath(s) {
  switch (s.kind) {
    case "circle":
      return `M${r2(s.cx - s.r)},${r2(s.cy)} a${s.r},${s.r} 0 1,0 ${r2(2 * s.r)},0 a${s.r},${s.r} 0 1,0 ${r2(-2 * s.r)},0 Z`;
    case "rect": {
      const { x, y, w, h } = s;
      const r = Math.min(s.r, w / 2, h / 2);
      return `M${r2(x + r)},${r2(y)} H${r2(x + w - r)} A${r},${r} 0 0,1 ${r2(x + w)},${r2(y + r)} V${r2(y + h - r)} A${r},${r} 0 0,1 ${r2(x + w - r)},${r2(y + h)} H${r2(x + r)} A${r},${r} 0 0,1 ${r2(x)},${r2(y + h - r)} V${r2(y + r)} A${r},${r} 0 0,1 ${r2(x + r)},${r2(y)} Z`;
    }
    case "line":
      return `M${s.x1},${s.y1} L${s.x2},${s.y2}`;
    default:
      return s.d;
  }
}

function paint(attr, value, mono) {
  if (mono) return { inline: `android:${attr}="#FFFFFFFF"`, nested: "" };
  const m = /^url\(#(\w+)\)$/.exec(value);
  if (!m) return { inline: `android:${attr}="${color(value)}"`, nested: "" };
  const g = GRADIENTS[m[1]];
  return {
    inline: "",
    nested: `
    <aapt:attr name="android:${attr}">
      <gradient android:type="linear" android:startX="${g.x1}" android:startY="${g.y1}" android:endX="${g.x2}" android:endY="${g.y2}" android:startColor="${color(g.from)}" android:endColor="${color(g.to)}"/>
    </aapt:attr>`,
  };
}

function vector(key, { mono = false } = {}) {
  const paths = ICONS[key].shapes
    .filter((s) => !(mono && ((s.kind !== "line" && /^#[0-9a-fA-F]{8}$/.test(s.fill)) || false)))
    .map((s) => {
      const d = shapePath(s);
      if (s.kind === "line") {
        const p = paint("strokeColor", s.stroke, mono);
        return `  <path android:pathData="${d}" android:strokeWidth="${s.width}" android:strokeLineCap="round" ${p.inline}>${p.nested}\n  </path>`;
      }
      const p = paint("fillColor", s.fill, mono);
      return `  <path android:pathData="${d}" ${p.inline}>${p.nested}\n  </path>`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-android-icons.mjs from src/icons/defs.ts. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="64dp"
    android:height="64dp"
    android:viewportWidth="64"
    android:viewportHeight="64">
${paths}
</vector>
`;
}

for (const key of Object.keys(ICONS)) {
  writeFileSync(`${out}/wx_${key.replace(/-/g, "_")}.xml`, vector(key));
}
// Notification icon: a white silhouette of the sun-and-cloud.
writeFileSync(
  `${out}/ic_stat_weather.xml`,
  vector("partly-day", { mono: true }).replace(/64dp/g, "24dp"),
);
console.log(`${Object.keys(ICONS).length + 1} drawables written to ${out}`);
